-- Night light (hyprsunset) — Lua source of truth.
--
-- hyprsunset is a separate daemon that only reads hyprsunset.conf. We keep that
-- file profile-free on purpose: the color temperature is not scheduled here
-- anymore. controllers/night_light_dynamic.py follows the real solar elevation
-- for the location in night_light.jsonc and pushes gradual temperatures through
-- `hyprctl hyprsunset temperature`, so the screen warms up when it actually
-- gets dark and cools down at sunrise.
--
-- This file only writes the static config and (re)starts hyprsunset.

local function write_conf()
  local conf_path = (os.getenv("HOME") or "") .. "/.config/hypr/hyprsunset.conf"
  local file = io.open(conf_path, "w")
  if file then
    file:write("# Generated by hyprsunset.lua — edit the Lua profiles, not this file.\n")
    file:write("# No time profiles: temperature is driven dynamically by\n")
    file:write("# controllers/night_light_dynamic.py (solar elevation, see night_light.jsonc).\n")
    file:close()
  end
end

hl.on("hyprland.start", function()
  write_conf()
  hl.exec_cmd("pkill -x hyprsunset; setsid uwsm-app -- hyprsunset >/dev/null 2>&1 &")
end)
